class ReviewRunRepository:
    """
    Persistent repository for full-application review runs.
    Preserves historical runs and enables direct retrieval by review ID or application ID.
    """
    def __init__(self, data_dir: Optional[str] = None):
        self._reviews_by_id: Dict[str, ReviewReport] = {}
        self._reviews_by_app: Dict[str, List[ReviewReport]] = {}
        self._active_locks: Set[str] = set()
        self._lock = threading.Lock()
        self._path: Optional[str] = None
        data_dir = ensure_dir(data_dir)
        if data_dir:
            self._path = os.path.join(data_dir, "review_runs.jsonl")
            for rec in read_jsonl(self._path):
                self._index(ReviewReport(**rec))

    def _index(self, report: "ReviewReport") -> None:
        self._reviews_by_id[report.review_id] = report
        self._reviews_by_app.setdefault(report.application_id, []).append(report)

    def acquire_lock(self, application_id: str) -> bool:
        with self._lock:
            if application_id in self._active_locks:
                return False
            self._active_locks.add(application_id)
            return True

    def release_lock(self, application_id: str):
        with self._lock:
            self._active_locks.discard(application_id)

    def is_locked(self, application_id: str) -> bool:
        with self._lock:
            return application_id in self._active_locks

    def save(self, report: ReviewReport) -> ReviewReport:
        with self._lock:
            self._index(report)
            if self._path:
                append_jsonl(self._path, report.model_dump(mode="json"))
            return report

    def get_by_id(self, review_id: str) -> Optional[ReviewReport]:
        return self._reviews_by_id.get(review_id)

    def get_latest_by_application_id(self, application_id: str) -> Optional[ReviewReport]:
        runs = self._reviews_by_app.get(application_id, [])
        return runs[-1] if runs else None

    def list_by_application_id(self, application_id: str) -> List[ReviewReport]:
        return self._reviews_by_app.get(application_id, [])

global_review_repository = ReviewRunRepository(data_dir=settings.DATA_DIR or None)

class CoverageAuditor:
    """
    Independent Coverage Auditor.
    Compares the planned checklist of checks against recorded execution results.
    Does NOT trust summary tallies; independently verifies that every planned check
    has a terminal outcome.
    """
    @staticmethod
    def audit(
        planned_checks: List[CheckPlanItem],
        executed_findings: List[Finding],
        verifications: List[VerificationAttemptRecord]
    ) -> CoverageAuditReport:
        planned_ids = {c.check_id for c in planned_checks}
        
        # Collect executed IDs from findings and verification attempts
        executed_ids: Set[str] = set()
        
        # Rule findings
        for f in executed_findings:
            executed_ids.add(f.rule_id)
            
        # Verification adapter attempts
        for v in verifications:
            executed_ids.add(f"VERIFY_{v.adapter_name}_{v.document_type.value}")

        missing = planned_ids - executed_ids
        unaccounted = executed_ids - planned_ids
        
        total_planned = len(planned_ids)
        total_accounted = len(planned_ids & executed_ids)
        
        coverage_pct = (total_accounted / total_planned * 100.0) if total_planned > 0 else 100.0
        is_complete = (len(missing) == 0 and total_accounted == total_planned)
        
        verdict = "COMPLETE" if is_complete else "INCOMPLETE"
        
        notes = (
            f"Coverage Audit: {total_accounted}/{total_planned} planned checks accounted for "
            f"({coverage_pct:.1f}%). "
        )
        if missing:
            notes += f"Missing checks: {', '.join(sorted(missing))}."
        else:
            notes += "All planned checks reached terminal outcomes."
            
        return CoverageAuditReport(
            is_complete=is_complete,
            audit_verdict=verdict,
            total_planned=total_planned,
            total_accounted=total_accounted,
            missing_checks=sorted(list(missing)),
            unaccounted_checks=sorted(list(unaccounted)),
            coverage_percentage=round(coverage_pct, 2),
            audit_notes=notes
        )

class ReviewOrchestrator:
    """
    Automatic Full-Application Review Orchestrator.
    Manages the complete end-to-end pre-scrutiny pipeline.
    """
    def __init__(
        self,
        repository: Optional[ReviewRunRepository] = None,
        duplicate_detector: Optional[DuplicateDetector] = None,
        auditor: Optional[CoverageAuditor] = None
    ):
        self.repository = repository or global_review_repository
        self.duplicate_detector = duplicate_detector or DuplicateDetector()
        self.auditor = auditor or CoverageAuditor()

    def build_check_plan(
        self,
        application: ApplicationInput,
        rules: List[BaseRule]
    ) -> List[CheckPlanItem]:
        """
        Enumerates every planned check before execution.
        """
        plan: List[CheckPlanItem] = []
        
        # 1. Planned Regulatory Rules
        for r in rules:
            plan.append(
                CheckPlanItem(
                    check_id=r.rule_id,
                    check_type="REGULATORY_RULE",
                    name=r.meta.name,
                    description=r.meta.explanation,
                    target_entity=r.meta.source_citation,
                    expected_inputs=r.meta.required_field_keys + [d.value for d in r.meta.required_document_types]
                )
            )
            
        # 2. Planned External Verification Adapters
        for doc in application.documents:
            adapter = get_adapter_for_document_type(doc.document_type)
            if adapter:
                plan.append(
                    CheckPlanItem(
                        check_id=f"VERIFY_{adapter.adapter_name}_{doc.document_type.value}",
                        check_type="ISSUER_VERIFICATION",
                        name=f"External Issuer Verification ({doc.document_type.value})",
                        description=f"Query {adapter.adapter_name} for document reference authenticity",
                        target_entity=doc.id,
                        expected_inputs=[doc.original_filename]
                    )
                )
                
        # 3. Planned Cross-Application Duplicate Scan
        plan.append(
            CheckPlanItem(
                check_id="RULE-APH-REUSE-010",
                check_type="DUPLICATE_DETECTION",
                name="Cross-Application Document Reuse Scan",
                description="Checks repository index for identical SHA-256 binary files in other dossiers",
                target_entity=application.application_id,
                expected_inputs=["Document SHA-256 checksums"]
            )
        )
        
        return plan

    def run_complete_prescrutiny(
        self,
        application: ApplicationInput,
        rule_pack_id: str = "rp-aicte-aph-2024-eoa",
        rule_pack_version: str = "1.0.0",
        custom_rules: Optional[List[BaseRule]] = None,
        simulated_context: Optional[Dict[str, Any]] = None,
        force_omit_check_id: Optional[str] = None # Used for negative coverage testing
    ) -> ReviewReport:
        """
        Executes full pre-scrutiny review workflow.
        Guarantees coverage reconciliation and idempotency.
        """
        app_id = application.application_id
        
        # Guard against concurrent duplicate execution
        if not self.repository.acquire_lock(app_id):
            raise RuntimeError(
                f"Concurrent review rejected: A pre-scrutiny run is already in progress for application '{app_id}'."
            )

        try:
            # 1. Input Snapshot & Hash
            input_hash = ValidationEngine.compute_input_snapshot_hash(application)
            rules = custom_rules if custom_rules is not None else get_default_rules(pack_version=rule_pack_version)
            
            # 2. Document Processing State Guard
            # Verify no documents are in an unhandled PROCESSING state
            for doc in application.documents:
                # If document has poor quality / unreadable extraction, ensure it's not silently lost
                for field in doc.extracted_fields:
                    if field.confidence < 0.65:
                        doc.verification_status = DocumentVerificationStatus.MANUAL_REVIEW_REQUIRED

            # 3. Enumerate Planned Checks
            planned_checks = self.build_check_plan(application, rules)
            
            # 4. Execute Rule Engine
            all_findings: List[Finding] = []
            errors: List[str] = []

            for r in rules:
                # Omission injection for coverage test
                if force_omit_check_id and r.rule_id == force_omit_check_id:
                    continue
                try:
                    finding = r.evaluate(application)
                    all_findings.append(finding)
                except Exception as exc:
                    err_msg = f"Exception evaluating {r.rule_id}: {str(exc)}"
                    errors.append(err_msg)
                    all_findings.append(
                        Finding(
                            rule_id=r.rule_id,
                            rule_version=r.rule_version,
                            rule_name=r.meta.name,
                            clause_citation=r.meta.source_citation,
                            is_demo=r.meta.is_demo,
                            status=FindingStatus.INCONCLUSIVE,
                            severity=r.meta.severity,
                            reason=f"Check execution failed due to internal error: {str(exc)}",
                            recommended_action="System inspection required.",
                            evidence=[]
                        )
                    )

            # 5. Execute External Issuer Verification Adapters
            verifications: List[VerificationAttemptRecord] = []
            for doc in application.documents:
                adapter = get_adapter_for_document_type(doc.document_type)
                if adapter:
                    check_id = f"VERIFY_{adapter.adapter_name}_{doc.document_type.value}"
                    if force_omit_check_id and check_id == force_omit_check_id:
                        continue
                    
                    ref_id = "REF-" + doc.sha256_hash[:8].upper()
                    if doc.verification_status == DocumentVerificationStatus.SOURCE_UNAVAILABLE:
                        ctx = {"simulated_mode": "source_unavailable"}
                    elif doc.verification_status == DocumentVerificationStatus.EXPIRED:
                        ctx = {"simulated_mode": "expired"}
                    else:
                        ctx = simulated_context or {}

                    attempt = adapter.verify(
                        document_id=doc.id,
                        document_type=doc.document_type,
                        reference_id=ref_id,
                        context=ctx
                    )
                    verifications.append(attempt)
                    # Update document verification status based on attempt
                    doc.verification_status = attempt.status

            # 6. Execute Cross-Application Duplicate Scan
            duplicate_findings = self.duplicate_detector.check_application_duplicates(application)
            if not (force_omit_check_id and force_omit_check_id == "RULE-APH-REUSE-010"):
                if duplicate_findings:
                    all_findings.extend(duplicate_findings)
                else:
                    # Record compliant duplicate check
                    all_findings.append(
                        Finding(
                            rule_id="RULE-APH-REUSE-010",
                            rule_version="1.0.0",
                            rule_name="Cross-Application Document Reuse Scan",
                            clause_citation="[DEMO_RULE] PRAMAAN-AI Cross-Application Reuse Detection Norms v1.0",
                            is_demo=True,
                            status=FindingStatus.COMPLIANT,
                            severity=Severity.OBSERVATION,
                            reason="No duplicate document reuse detected across repository applications.",
                            recommended_action="No action required.",
                            evidence=[]
                        )
                    )

            # 7. Independent Coverage Audit
            coverage_audit = self.auditor.audit(
                planned_checks=planned_checks,
                executed_findings=all_findings,
                verifications=verifications
            )

            # 8. Categorize Outcomes
            findings_list = [f for f in all_findings if f.status in [FindingStatus.DEFICIENCY, FindingStatus.ANOMALY_SIGNAL]]
            successful_list = [f for f in all_findings if f.status == FindingStatus.COMPLIANT]
            not_applicable_list = [f for f in all_findings if f.status == FindingStatus.NOT_APPLICABLE]
            inconclusive_list = [f for f in all_findings if f.status == FindingStatus.INCONCLUSIVE]

            # Unresolved tasks
            unresolved = []
            for f in findings_list:
                unresolved.append(f"[{f.severity.value}] {f.rule_name}: {f.recommended_action}")
            for inc in inconclusive_list:
                unresolved.append(f"[MANUAL_REVIEW] {inc.rule_name}: {inc.recommended_action}")
            for v in verifications:
                if v.status in [DocumentVerificationStatus.SOURCE_UNAVAILABLE, DocumentVerificationStatus.MANUAL_REVIEW_REQUIRED]:
                    unresolved.append(f"[SOURCE_{v.status.value.upper()}] Verification for {v.document_type.value}: {v.error_message or 'Manual check needed'}")

            # Overall review status
            if not coverage_audit.is_complete:
                review_status = "INCOMPLETE"
            elif any(f.status == FindingStatus.DEFICIENCY for f in all_findings):
                review_status = "COMPLETE_WITH_DEFICIENCIES"
            elif any(f.status == FindingStatus.ANOMALY_SIGNAL for f in all_findings):
                review_status = "COMPLETE_WITH_ANOMALIES"
            else:
                review_status = "COMPLETE_COMPLIANT"

            summary_tallies = {
                "total_planned": len(planned_checks),
                "total_executed": len(all_findings) + len(verifications),
                "deficiencies": sum(1 for f in all_findings if f.status == FindingStatus.DEFICIENCY),
                "anomalies": sum(1 for f in all_findings if f.status == FindingStatus.ANOMALY_SIGNAL),
                "compliant": len(successful_list),
                "not_applicable": len(not_applicable_list),
                "inconclusive": len(inconclusive_list),
                "source_verifications": len(verifications),
                "unresolved_tasks": len(unresolved)
            }

            # Cryptographic audit hash simulation for this review run
            audit_payload = f"{app_id}|{input_hash}|{review_status}|{len(all_findings)}"
            audit_hash = hashlib.sha256(audit_payload.encode("utf-8")).hexdigest()

            report = ReviewReport(
                review_id=str(uuid.uuid4()),
                application_id=application.application_id,
                application_number=application.application_number,
                academic_year=application.academic_year,
                category=application.category.value,
                rule_pack_id=rule_pack_id,
                rule_pack_version=rule_pack_version,
                executed_at=datetime.now(timezone.utc),
                input_snapshot_hash=input_hash,
                review_status=review_status,
                planned_checks=planned_checks,
                coverage_audit=coverage_audit,
                findings=findings_list,
                successful_checks=successful_list,
                not_applicable_checks=not_applicable_list,
                inconclusive_checks=inconclusive_list,
                source_verifications=verifications,
                summary=summary_tallies,
                unresolved_tasks=unresolved,
                audit_chain_event_hash=audit_hash,
                errors=errors
            )

            # Persist run
            self.repository.save(report)
            return report

        finally:
            self.repository.release_lock(app_id)
